    //#Region cargar y guardar archivos
    private void cargarPlano(File archivo){
        //se limpia el plano actual y se crea uno nuevo
        Plano p = new Plano();
        int numeroL = 1;
        
        //se lee el archivo
        try (BufferedReader br = new BufferedReader(new FileReader(archivo))){
            String linea;
            
            //se recorre el archivo
            while ((linea = br.readLine()) != null) { 
                //lineas vacías o que inician con # se ignoran
                if(linea.trim().isEmpty() || linea.charAt(0) == '#'){
                    numeroL++;
                    continue;
                }
                
                //se splitea la linea
                String[] s = linea.split("\\;");
                
                //se valida el formato
                if(!s[0].equalsIgnoreCase("LUGAR") && !s[0].equalsIgnoreCase("TRAMO"))
                    throw new Exception("El archivo contiene un tipo desconocido - " 
                            + s[0]);
                
                if(s[0].equalsIgnoreCase("LUGAR")){
                    cargarObjetoLugar(p,s);
                }
                else{
                    cargarObjetoTramo(p, s);
                }
                numeroL++;
            }
            
            //se valida que haiga al menos un lugar de salida en el plano
            if(!planoTieneTipoDeLugar(p, "Fin"))
                throw new IllegalArgumentException("El plano no cuenta con ninguna salida");
            
            //Se cambia el plano actual por el cargado
            planoActual = p;
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage() + " -> linea: " + numeroL);
        }
        
        refrescarTablaLugares(planoActual.getLugares());
        refrescarTablaTramos(planoActual.getTramos());
    }
    private void guardarPlano(){        
        //se sobreescribe el archivo
        try (PrintWriter pw = new PrintWriter(new FileWriter(archivoPlano))){
            //se recorre la lista de lugares del plano
            for (Lugar lugar : planoActual.getLugares()) {
                pw.append(lugar.lineaArchivo()+"\n");
            }
            //se recorre la lista de tramos del plano
            for (Tramo tramo : planoActual.getTramos()) {
                pw.append(tramo.lineaArchivo()+"\n");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrio un error al guardar el plano: " + e.getMessage());
        }
    }
    private void cargarHistorial(){
        File f = new File(archivoSimulaciones);
        if(!f.exists()){
            JOptionPane.showMessageDialog(this, "No se ha realizado ninguna simulación");
            return;
        }
        
        try (ObjectInputStream ois = new ObjectInputStream(new FileInputStream(f))){
            //se deserealiza el objeto
            simulaciones = (ArrayList<Simulacion>) ois.readObject();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrio un error al cargar el archivo");
        }
    }
    private void guardarSimulacion(){
        //se guarda el archivo de simulaciones
        try (ObjectOutputStream oop = new ObjectOutputStream(new FileOutputStream(archivoSimulaciones))){
            oop.writeObject(simulaciones);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Ocurrio un error al guardar el archivo");
        }
    }
